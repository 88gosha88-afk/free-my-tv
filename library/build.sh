#!/usr/bin/env bash
# Builds FreeMyLibrary.apk without Gradle: downloads the libraries once (jcifs-ng for the network folder, and slf4j and
# BouncyCastle, which it needs; libVLC for the built-in player, about 100 MB), then aapt2 -> javac -> d8 -> zipalign ->
# apksigner. Needs a JDK 17+, the Android SDK command-line tools (build-tools 34+, platform android-34), curl, zip, unzip.
set -euo pipefail
cd "$(dirname "$0")"

# --- Tools
SDK="${ANDROID_HOME:-${ANDROID_SDK_ROOT:-}}"
if [ -z "$SDK" ]; then
  for d in "$HOME/Library/Android/sdk" "$HOME/Android/Sdk" /opt/homebrew/share/android-commandlinetools \
           /usr/local/share/android-commandlinetools /usr/lib/android-sdk; do
    if [ -d "$d/build-tools" ]; then SDK="$d"; break; fi
  done
fi
[ -n "$SDK" ] && [ -d "$SDK/build-tools" ] || { echo "Android SDK not found. Install it and set ANDROID_HOME (see ../README.md)."; exit 1; }
BT="$SDK/build-tools/$(ls "$SDK/build-tools" | sort -V | tail -1)"
AJ="$(ls -d "$SDK"/platforms/android-*/android.jar 2>/dev/null | sort -V | tail -1 || true)"
[ -f "${AJ:-}" ] || { echo "Android platform not found. Run: sdkmanager \"platforms;android-34\""; exit 1; }
# The Android build tools (d8) are older than the newest Java: on Java 22 and later d8 crashes inside itself
# (NullPointerException in R8). Use a Java 17, 21 or 11 when the Mac has one; JAVA_HOME wins if it is set.
if [ -z "${JAVA_HOME:-}" ] && [ -x /usr/libexec/java_home ]; then
  for v in 17 21 11; do
    J="$(/usr/libexec/java_home -v "$v" 2>/dev/null || true)"
    if [ -n "$J" ] && [ -x "$J/bin/javac" ]; then export JAVA_HOME="$J"; echo "Using Java $v ($J)"; break; fi
  done
fi
JAVAC="${JAVA_HOME:+$JAVA_HOME/bin/}javac"
KEYTOOL="${JAVA_HOME:+$JAVA_HOME/bin/}keytool"
command -v "$JAVAC" >/dev/null 2>&1 || { echo "JDK not found. Install JDK 17 and set JAVA_HOME."; exit 1; }
for t in curl zip unzip; do command -v $t >/dev/null 2>&1 || { echo "$t not found."; exit 1; }; done

# --- Libraries (downloaded once into libs/)
MAVEN="https://repo1.maven.org/maven2"
mkdir -p libs
fetch() {   # fetch <url> <file>
  [ -s "$2" ] && return 0
  echo "Downloading $(basename "$2")…"
  curl -fL --retry 3 -o "$2.part" "$1" && mv "$2.part" "$2" || { rm -f "$2.part"; echo "Could not download $1"; exit 1; }
}
fetch "$MAVEN/eu/agno3/jcifs/jcifs-ng/2.1.10/jcifs-ng-2.1.10.jar" libs/jcifs-ng.jar
fetch "$MAVEN/org/slf4j/slf4j-api/1.7.36/slf4j-api-1.7.36.jar" libs/slf4j-api.jar
fetch "$MAVEN/org/bouncycastle/bcprov-jdk18on/1.78.1/bcprov-jdk18on-1.78.1.jar" libs/bcprov.jar
# Only the annotations that libVLC's classes carry: helpful for the compiler, not needed to run. Skipped if not reachable.
if [ ! -s libs/annotation.jar ]; then
  curl -fsL --retry 2 -o libs/annotation.jar.part "https://dl.google.com/android/maven2/androidx/annotation/annotation-jvm/1.7.1/annotation-jvm-1.7.1.jar" \
    && mv libs/annotation.jar.part libs/annotation.jar || rm -f libs/annotation.jar.part
fi
ANNOT=""; [ -s libs/annotation.jar ] && ANNOT="libs/annotation.jar"

# --- Settings: config.properties -> Config.java
if [ ! -f config.properties ]; then
  cp config.example.properties config.properties
  echo "Created library/config.properties: check the network folder and the folders there, then build again."
fi
prop() {   # prop <name> <default>: the last "name=value" of config.properties (the value may hold spaces and quotes)
  local v
  v="$(grep -E "^[[:space:]]*$1[[:space:]]*=" config.properties | tail -1 | cut -d= -f2- || true)"
  v="$(printf '%s' "$v" | sed -e 's/^[[:space:]]*//' -e 's/[[:space:]]*$//')"
  printf '%s' "${v:-$2}"
}
java_string() { printf '%s' "$1" | sed -e 's/\\/\\\\/g' -e 's/"/\\"/g'; }
# --- libVLC (the built-in player): the AAR holds the Java classes and the native libraries for each processor
VLC_VERSION="$(prop libvlc_version 3.6.0)"
ABIS="$(prop abis 'armeabi-v7a,arm64-v8a')"
fetch "$MAVEN/org/videolan/android/libvlc-all/$VLC_VERSION/libvlc-all-$VLC_VERSION.aar" "libs/libvlc-$VLC_VERSION.aar"
VLC_DIR="libs/libvlc-$VLC_VERSION"
[ -f "$VLC_DIR/classes.jar" ] || { mkdir -p "$VLC_DIR" && unzip -qo "libs/libvlc-$VLC_VERSION.aar" -d "$VLC_DIR"; }
CP="$AJ:libs/jcifs-ng.jar:libs/slf4j-api.jar:libs/bcprov.jar:$VLC_DIR/classes.jar${ANNOT:+:$ANNOT}"

TMDB="$(prop tmdb_key '')"
if [ -z "$TMDB" ] && [ -f ../config.properties ]; then
  TMDB="$(grep -E '^[[:space:]]*tmdb_key[[:space:]]*=' ../config.properties | tail -1 | cut -d= -f2- | tr -d ' \r' || true)"
fi

rm -rf out && mkdir -p out/gen/io/freemytv/library out/classes out/apk
cat > out/gen/io/freemytv/library/Config.java <<EOF
package io.freemytv.library;

/** Generated by build.sh from config.properties: edit that file, not this one. */
final class Config {
    private Config() {}

    static final String SMB_URL = "$(java_string "$(prop smb_url 'smb://192.168.1.1/')")";
    static final String SMB_USER = "$(java_string "$(prop smb_user '')")";
    static final String SMB_PASSWORD = "$(java_string "$(prop smb_password '')")";
    static final String FOLDERS = "$(java_string "$(prop folders '')")";
    static final String TMDB_KEY = "$(java_string "$TMDB")";
}
EOF

# --- Build
"$BT/aapt2" compile --dir res -o out/res.zip
"$BT/aapt2" link -o out/base.apk -I "$AJ" --manifest AndroidManifest.xml --java out/gen out/res.zip \
  --min-sdk-version 28 --target-sdk-version 33
"$JAVAC" -nowarn -Xlint:-options -source 8 -target 8 -bootclasspath "$AJ:$BT/core-lambda-stubs.jar" -classpath "$CP" \
  -encoding UTF-8 -d out/classes $(find src out/gen -name '*.java')
"$BT/d8" --release --min-api 28 --lib "$AJ" ${ANNOT:+--lib $ANNOT} --output out/apk $(find out/classes -name '*.class') \
  libs/jcifs-ng.jar libs/slf4j-api.jar libs/bcprov.jar "$VLC_DIR/classes.jar"
IFS=',' read -r -a ABI_LIST <<< "$ABIS"
for abi in "${ABI_LIST[@]}"; do
  abi="$(printf '%s' "$abi" | tr -d ' ')"
  [ -d "$VLC_DIR/jni/$abi" ] || { echo "libVLC $VLC_VERSION has no libraries for '$abi'."; exit 1; }
  mkdir -p "out/apk/lib/$abi" && cp "$VLC_DIR/jni/$abi/"*.so "out/apk/lib/$abi/"
done
(cd out/apk && zip -qr ../base.apk classes*.dex lib)
"$BT/zipalign" -f -p 4 out/base.apk out/aligned.apk

# --- Sign with your own key (created once; updates need the same key, so keep library.keystore)
if [ ! -f library.keystore ]; then
  "$KEYTOOL" -genkeypair -keystore library.keystore -alias library -keyalg RSA -keysize 2048 -validity 20000 \
    -storepass freemylibrary -keypass freemylibrary -dname "CN=Free My Library" >/dev/null 2>&1
fi
"$BT/apksigner" sign --ks library.keystore --ks-pass pass:freemylibrary --key-pass pass:freemylibrary --out FreeMyLibrary.apk out/aligned.apk
echo "Built FreeMyLibrary.apk ($(du -h FreeMyLibrary.apk | cut -f1)). Install: adb install -r FreeMyLibrary.apk"
